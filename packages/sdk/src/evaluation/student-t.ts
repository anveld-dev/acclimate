export function studentTCritical(cases: number, audit: boolean): number {
  const df = cases - 1;
  if (df < 1) return Infinity;
  if (df <= quantiles.length) return quantiles[df - 1][audit ? 2 : 1];
  const z = audit ? 1.6448536269514722 : 1.2815515655446004;
  const z2 = z * z;
  return (
    z +
    (z * (z2 + 1)) / (4 * df) +
    (z * (5 * z2 * z2 + 16 * z2 + 3)) / (96 * df ** 2) +
    (z * (3 * z2 ** 3 + 19 * z2 * z2 + 17 * z2 - 15)) / (384 * df ** 3)
  );
}
