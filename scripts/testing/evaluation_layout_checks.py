"""Interaction checks for the paired case ledger; all outcomes are fixture data."""
import math
from playwright.sync_api import expect
from scripts.bdd.layout import capture_layout
from scripts.testing.compact_console import visit


def verify(w,b,p,route,out,checks):
    count=len(w.settings['expectedCases'])
    p.set_viewport_size(dict(width=1440,height=1000));visit(p,b,route)
    e=p.locator('.comparison-evidence');table=e.get_by_role('table',name='Evaluation case outcomes',exact=True)
    rows=e.locator('.evaluation-pair-summary')
    expect(rows).to_have_count(25)
    assert table.evaluate("e=>[...e.children].every(n=>['THEAD','TBODY'].includes(n.tagName))")
    assert table.evaluate("e=>[...e.querySelectorAll('tbody')].every(n=>[...n.children].every(c=>c.tagName==='TR'))")
    assert table.evaluate("e=>[...e.querySelectorAll('td[headers]')].every(c=>c.getAttribute('headers').split(' ').every(id=>!!document.getElementById(id)))")
    trigger=e.get_by_role('button',name='Inspect case retry-00 / 2',exact=True)
    detail=trigger.locator('xpath=ancestor::tbody').locator('.evaluation-pair-detail')
    expect(trigger).to_have_attribute('aria-expanded','false');expect(detail).to_be_hidden()
    trigger.focus();p.keyboard.press('Enter');expect(detail).to_be_visible();expect(trigger).to_be_focused()
    assert trigger.get_attribute('aria-controls')==detail.get_attribute('id')
    expect(detail).to_contain_text('task_failed');expect(detail).to_contain_text('-0.5')
    expect(detail).to_contain_text('long-error-');expect(detail).to_contain_text('artifact://fixture/reference-')
    expect(detail.get_by_role('link')).to_have_count(0)
    capture_layout(p,out,'paired-details-1440')
    p.keyboard.press('Enter');expect(detail).to_be_hidden();expect(trigger).to_be_focused()
    assert not detail.evaluate("e=>[...e.querySelectorAll('a,button,input,[tabindex]')].some(n=>n.getClientRects().length)")
    first_pair=e.get_by_role('button',name='Inspect case retry-00 / 0',exact=True)
    first_pair.click();e.locator('.evaluation-case-toolbar').evaluate("e=>e.scrollIntoView({block:'start'})")
    capture_layout(p,out,'paired-reading-1440');first_pair.click()
    missing=e.get_by_role('button',name='Inspect case retry-00 / 1',exact=True)
    missing.click();md=p.locator('[id="'+missing.get_attribute('aria-controls')+'"]')
    expect(md).to_contain_text('infrastructure_failed');expect(md).to_contain_text('missing');expect(md).to_contain_text('unknown')
    missing.click()
    unknown=e.get_by_role('button',name='Inspect case retry-00 / 3',exact=True)
    unknown.click();ud=p.locator('[id="'+unknown.get_attribute('aria-controls')+'"]');expect(ud).to_contain_text('unknown');unknown.click()
    checks.append('Valid table row groups and header bindings; paired disclosure keyboard/focus, hidden content, signed graded failure, missing grades, unknown cost and literal references')

    search=e.get_by_label('Search evaluation cases',exact=True)
    search.fill('retry-00 / 2');expect(rows).to_have_count(1);expect(rows).to_contain_text('task_failed')
    search.fill('absent-case');expect(rows).to_have_count(0);expect(e.get_by_text('No cases match this view.',exact=True)).to_be_visible()
    capture_layout(p,out,'no-matching-cases')
    e.get_by_role('button',name='Clear search',exact=True).click();expect(search).to_be_focused();expect(rows).to_have_count(25)
    lower=e.get_by_role('radio',name='Lower reward',exact=False);lower.click()
    assert 0<rows.count()<=25
    for text in rows.locator('.pair-change').all_text_contents():assert text=='Lower reward',text
    e.get_by_role('radio',name='All '+str(count),exact=True).click()
    grid=e.get_by_role('group',name='Expected case pairs',exact=True)
    first=grid.locator('button').first;first.hover();expect(p.get_by_role('tooltip')).to_contain_text('retry-00 / 0')
    first.focus();p.keyboard.press('Escape');expect(p.get_by_role('tooltip')).to_have_count(0)
    p.keyboard.press('ArrowRight');expect(grid.locator('button').nth(1)).to_be_focused()
    p.keyboard.press('Enter');expect(rows).to_have_count(1);expect(rows).to_contain_text('retry-00 / 1')
    e.get_by_role('button',name='Show all pairs',exact=True).click()
    expect(e.get_by_role('group',name='Case results',exact=True)).to_be_focused();expect(rows).to_have_count(25)
    e.get_by_role('button',name='Next cases',exact=True).click();expect(e).to_contain_text(f'26–50 of {count} pairs')
    search.fill('retry-00 / 0');expect(rows).to_have_count(1);expect(e).to_contain_text('1–1 of 1 pairs')
    e.get_by_role('button',name='Clear search',exact=True).click()
    checks.append('Category filtering, repeated-ID search, zero-match clearing, hover/Escape, roving map selection, return focus and 25-pair paging/reset')

    if count>256:
        expect(grid.locator('button')).to_have_count(256)
        e.get_by_role('button',name=f'Show all {count} pairs',exact=True).click();expect(grid.locator('button')).to_have_count(count)
        grid.locator('button').first.focus();p.keyboard.press('End');expect(grid.locator('button').last).to_be_focused()
        assert grid.evaluate('e=>e.scrollHeight>e.clientHeight && e.clientHeight<=218 && e.scrollTop>0')
        assert grid.locator('button[tabindex="0"]').count()==1
        p.keyboard.press('Enter');expect(rows).to_have_count(1)
        expect(rows).to_contain_text(w.settings['expectedCases'][-1]['caseId'])
        e.get_by_role('button',name='Show first 256 pairs',exact=True).click()
        expect(grid.locator('button')).to_have_count(256);expect(rows).to_have_count(1)
        e.get_by_role('button',name='Show all pairs',exact=True).click()
        capture_layout(p,out,'large-bounded-map')
        checks.append('600+ inventory: bounded grid, End scroll/focus, one tab stop, selection beyond preview retained on collapse')

    for _ in range(math.ceil(count/25)-1):e.get_by_role('button',name='Next cases',exact=True).click()
    expect(e.get_by_role('button',name='Next cases',exact=True)).to_be_disabled()
    expect(e).to_contain_text(f'{(math.ceil(count/25)-1)*25+1}–{count} of {count} pairs')
    checks.append('Final page boundary keeps absent expected outcomes visible without turning them into zero')

    for width in [1440,1024,390,320]:
        p.set_viewport_size(dict(width=width,height=1000));visit(p,b,route)
        trigger=e.get_by_role('button',name='Inspect case retry-00 / 2',exact=True);trigger.click()
        detail=p.locator('[id="'+trigger.get_attribute('aria-controls')+'"]');detail.scroll_into_view_if_needed()
        assert p.evaluate('document.documentElement.scrollWidth<=innerWidth+1')
        assert detail.evaluate('e=>e.scrollWidth<=e.clientWidth+1')
        assert e.locator('.evaluation-pair-sides').first.evaluate('e=>e.scrollWidth<=e.clientWidth+1')
        expect(detail.get_by_role('heading',name='Parent',exact=True)).to_be_visible()
        expect(detail.get_by_role('heading',name='Candidate',exact=True)).to_be_visible()
        capture_layout(p,out,f'expanded-pair-{width}')
        search.fill('retry-long-');expect(rows).to_have_count(1)
        long_trigger=rows.get_by_role('button');long_trigger.focus();p.keyboard.press('Enter')
        assert long_trigger.evaluate('e=>e.scrollWidth<=e.clientWidth+1')
        assert rows.locator('.pair-change').evaluate('e=>e.scrollWidth<=e.clientWidth+1')
        assert p.evaluate('document.documentElement.scrollWidth<=innerWidth+1')
        capture_layout(p,out,f'long-case-{width}')
    # Constrain the actual evidence container independently of viewport width.
    p.set_viewport_size(dict(width=1440,height=1000));visit(p,b,route)
    e.evaluate("e=>e.style.width='280px'")
    trigger=e.get_by_role('button',name='Inspect case retry-00 / 2',exact=True);trigger.click()
    assert rows.first.evaluate("e=>getComputedStyle(e).display==='grid'")
    assert e.evaluate('e=>e.scrollWidth<=e.clientWidth+1')
    capture_layout(p,out,'embedded-280-results')
    checks.append('Expanded/long pair reflow at 1440/1024/390/320 and embedded 280px evidence; full identities and both sides remain reachable')

    p.set_viewport_size(dict(width=1440,height=1000));visit(p,b,route)
    e.get_by_role('button',name='Evidence details',exact=True).click()
    for value in [w.settings['parentVersionId'],w.settings['candidateVersionId'],w.evaluation['id'],w.settings['datasetRevision'],w.settings['graderRevision']]:expect(e).to_contain_text(value)
    expect(p.get_by_role('button',name='Review release with this evidence',exact=True)).to_be_disabled()
    # A real second immutable report exercises empty means and comparison reset.
    settings=dict(w.settings,datasetRevision='all-missing-layout-fixture')
    request=w.call('POST',w.bundle+'/evaluation-requests',dict(settings,requireBoundEvidence=True))
    path=w.bundle+'/evaluation-requests/'+request['id'];attempt='missing-layout-attempt'
    w.call('POST',path+'/start',dict(attemptId=attempt),actor='evaluator')
    report=w.call('POST',w.bundle+'/comparisons',dict(settings,evaluation=dict(requestId=request['id'],attemptId=attempt),results=[]),actor='evaluator')
    w.call('POST',path+'/finish',dict(attemptId=attempt,comparisonId=report['id']),actor='evaluator')
    visit(p,b,b.bundle_path('changes',candidate=w.draft['snapshotVersion']['id'],request=request['id'],comparison=report['id']))
    expect(search).to_have_value('');expect(rows).to_have_count(25)
    expect(e.get_by_role('radio',name='All '+str(count),exact=True)).to_be_checked()
    expect(e.locator('.evaluation-pair-detail').first).to_be_hidden()
    expect(p.get_by_role('region',name='Observed paired rewards',exact=True)).to_contain_text(f'0 / {count}')
    capture_layout(p,out,'all-missing-evidence')
    visit(p,b,b.bundle_path('changes',candidate=w.draft['snapshotVersion']['id'],request=w.queued['id']))
    expect(p.locator('.evaluation-request').filter(has_text=w.queued['id'])).to_contain_text('Ready')
    checks.append('Full provenance, unchanged partial-evidence release block, new immutable report resets inspection, zero-gradeable and queued states')

    w.sign_in('viewer','evaluation-layout-viewer')
    w.call('PUT',w.root+'/memberships/'+w.sessions['viewer']['userId'],dict(role='viewer'),actor='_browser-operator')
    context=b.browser.new_context(ignore_https_errors=True,viewport=dict(width=1440,height=1000))
    try:
        b.sign_in(context,'evaluation-layout-viewer');vp=context.new_page();vp.on('pageerror',lambda error:b.errors.append(str(error)));visit(vp,b,route)
        vt=vp.get_by_role('button',name='Inspect case retry-00 / 2',exact=True);vt.click()
        expect(vp.locator('[id="'+vt.get_attribute('aria-controls')+'"]')).to_be_visible()
        expect(vp.get_by_role('button',name='Review release with this evidence',exact=True)).to_be_disabled()
        capture_layout(vp,out,'read-only-pair-inspection')
    finally:context.close()
    checks.append('Read-only user can inspect paired details without release authority')
